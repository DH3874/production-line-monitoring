def flow(items, y, height=50):
    for i, (title, body) in enumerate(items):
        yy = y + i * (height + 10)
        rect(M, yy, 148, height, PALE)
        para(title, M + 12, yy + 14, 124, 10.2, TEAL, True)
        para(body, M + 165, yy + 8, CW - 165, 9.5)
        if i < len(items) - 1:
            arrow(M + 74, yy + height, M + 74, yy + height + 10)
    return y + len(items) * (height + 10) - 10

