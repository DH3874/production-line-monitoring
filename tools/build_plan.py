def para(text,x,top,w,size=10.2,color=INK,bold=False,leading=None):
    s=ParagraphStyle('p',fontName='KRB' if bold else 'KR',fontSize=size,leading=leading or size*1.58,textColor=color,wordWrap='CJK',spaceAfter=0)
