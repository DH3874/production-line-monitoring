def table(headers,rows,widths,y,size=9.1,pad=9):
    def p(t,head=False):
        return Paragraph(str(t),ParagraphStyle('cell',fontName='KRB' if head else 'KR',fontSize=size,leading=size*1.5,textColor=WHITE if head else INK,wordWrap='CJK'))
    data=[[p(v,True) for v in headers]]+[[p(v) for v in row] for row in rows]
    t=Table(data,colWidths=widths,hAlign='LEFT')
    cmds=[('BACKGROUND',(0,0),(-1,0),NAVY),('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),pad),('RIGHTPADDING',(0,0),(-1,-1),pad),('TOPPADDING',(0,0),(-1,-1),pad),('BOTTOMPADDING',(0,0),(-1,-1),pad),('LINEBELOW',(0,1),(-1,-1),.4,LINE)]
    for i in range(1,len(data)):
        if i%2:cmds.append(('BACKGROUND',(0,i),(-1,i),BG))
    t.setStyle(TableStyle(cmds)); _,h=t.wrap(CW,1000);t.drawOn(c,M,H-y-h)
    checks.append((page,y,y+h,'TABLE'))
    return y+h

def arrow(x1,y1,x2,y2,color=TEAL):
    import math
    c.setStrokeColor(color);c.setLineWidth(1.3);c.line(x1,H-y1,x2,H-y2)
    a=math.atan2(y2-y1,x2-x1)
    for off in [-.5,.5]:
        c.line(x2,H-y2,x2-6*math.cos(a+off),H-(y2-6*math.sin(a+off)))

